import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {createConnection} from 'node:net';
import {once} from 'node:events';
import os from 'node:os';
import path from 'node:path';
import {LiveSessions} from '../src/live/channel';
import {observe} from '../src/live/events';
import {sessionStatusLabel,turnStatusLabel,reviewLabels} from '../src/sessions/status';

test('状态按当前轮 ID 关联；不把旧轮、补丁或断线前状态当作正在执行',async t=>{
  for(const state of ['unclosed','empty','unknown'] as const)assert.equal(sessionStatusLabel({state}),'—');
  assert.equal(sessionStatusLabel({state:'finished'}),'已完成');
  assert.equal(sessionStatusLabel({state:'unclosed',live:{id:'s',state:'approval',at:1}}),'待批准');
  assert.equal(turnStatusLabel({outcome:'completed',liveState:'running'}),'已完成');
  assert.equal(turnStatusLabel({outcome:'unresolved',liveState:'input'}),'待回复');
  assert.equal(reviewLabels.baseline,'未审阅');
  const root=await mkdtemp(path.join(os.tmpdir(),'session-status-')),live=new LiveSessions();
  t.after(async()=>{await live.dispose();await rm(root,{recursive:true,force:true});});
  const client=createConnection(await live.start(root));t.after(()=>client.destroy());await once(client,'connect');
  const send=(message:unknown)=>client.write(JSON.stringify(message)+'\n');
  const until=async(check:()=>boolean)=>{const end=Date.now()+3000;while(!check()){if(Date.now()>end)throw new Error('状态通知未到达');await new Promise(resolve=>setTimeout(resolve,10));}};
  const event=(method:string,params:unknown)=>send({type:'event',event:observe(JSON.stringify({method,params}),100)});
  const status=(type:string,activeFlags:string[]=[])=>event('thread/status/changed',{threadId:'s',status:{type,activeFlags}});
  const start=(id:string)=>event('turn/started',{threadId:'s',turn:{id,startedAt:1}});
  const complete=(id:string)=>event('turn/completed',{threadId:'s',turn:{id,status:'completed',completedAt:2,durationMs:1000}});
  send({type:'snapshot',entries:[]});await until(()=>live.connected);
  status('active');await until(()=>live.entries.get('s')?.state==='running');assert.equal(live.turnState('s','a'),undefined);
  start('a');await until(()=>live.turnState('s','a')==='running');
  status('active',['waitingOnApproval']);await until(()=>live.turnState('s','a')==='approval');
  send({type:'event',event:{type:'patch',id:'s',turnId:'old',body:{item:{id:'p',at:1,status:'completed',files:[{path:'a.ts',kind:'update'}],bytes:0,fingerprint:'fixture'},patches:[]}}});
  await until(()=>!!live.turns.get('s')?.has('old'));assert.equal(live.turnState('s','old'),undefined);assert.equal(live.turnState('s','a'),'approval');
  complete('a');await until(()=>live.turns.get('s')?.get('a')?.outcome==='completed');assert.equal(live.turnState('s','a'),undefined);
  start('b');await until(()=>live.turnState('s','b')==='approval');start('a');complete('a');
  status('active',['waitingOnUserInput']);await until(()=>live.turnState('s','b')==='input');assert.equal(live.turnState('s','a'),undefined);
  status('idle');await until(()=>live.entries.get('s')?.state==='idle');status('active');await until(()=>live.entries.get('s')?.state==='running');assert.equal(live.turnState('s','b'),undefined);
  start('c');await until(()=>live.turnState('s','c')==='running');send({type:'snapshot',entries:[{id:'s',state:'running',at:200}]});
  await until(()=>live.entries.get('s')?.at===200);assert.equal(live.turnState('s','c'),undefined);
  start('d');await until(()=>live.turnState('s','d')==='running');client.end();await until(()=>!live.connected);assert.equal(live.turnState('s','d'),undefined);
});
